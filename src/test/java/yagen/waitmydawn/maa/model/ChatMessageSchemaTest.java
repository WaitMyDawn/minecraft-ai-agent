package yagen.waitmydawn.maa.model;

import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import java.sql.DriverManager;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class ChatMessageSchemaTest {
    @Test void schemaUpdateWidensExistingColumnAndPreservesLongStructuredHistory() throws Exception {
        String url = "jdbc:h2:mem:message-upgrade-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url, "sa", ""); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE maa_chat_message (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "conversationId BIGINT NOT NULL, role VARCHAR(255) NOT NULL, content VARCHAR(5000), "
                    + "hasData BOOLEAN NOT NULL, thinkTime VARCHAR(255), modSlugs VARCHAR(10000), snapshotId VARCHAR(16), "
                    + "packState VARCHAR(524288), createdAt TIMESTAMP NOT NULL)");
            statement.execute("INSERT INTO maa_chat_message(conversationId,role,content,hasData,createdAt) VALUES(1,'ai','old',false,CURRENT_TIMESTAMP)");
        }
        try (var factory = new Configuration().addAnnotatedClass(ChatMessage.class)
                .setProperty("hibernate.connection.url", url).setProperty("hibernate.connection.username", "sa")
                .setProperty("hibernate.connection.password", "").setProperty("hibernate.hbm2ddl.auto", "update")
                .buildSessionFactory()) {
            String content = "<requirement_report>" + "报告证据".repeat(12000) + "</requirement_report>";
            Long id;
            try (var session = factory.openSession()) {
                var tx = session.beginTransaction();
                var message = new ChatMessage(1L, "ai", content, true, "10.0", "core");
                session.persist(message); tx.commit(); id = message.getId();
            }
            try (var session = factory.openSession()) {
                assertEquals(content, session.find(ChatMessage.class, id).getContent());
                assertEquals("old", session.find(ChatMessage.class, 1L).getContent());
            }
        }
    }
}
