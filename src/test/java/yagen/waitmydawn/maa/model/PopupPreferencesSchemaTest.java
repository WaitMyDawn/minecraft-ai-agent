package yagen.waitmydawn.maa.model;

import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import java.sql.DriverManager;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class PopupPreferencesSchemaTest {
    @Test void existingAccountsDefaultToEnabledAndExplicitChoicesSurviveReload() throws Exception {
        String url = "jdbc:h2:mem:popup-upgrade-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url, "sa", ""); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE maa_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "accountNumber VARCHAR(255) NOT NULL, username VARCHAR(255), passwordHash VARCHAR(255) NOT NULL, "
                    + "createdAt TIMESTAMP NOT NULL, enableBlacklist BOOLEAN DEFAULT FALSE NOT NULL, enableUserFeedbackRules BOOLEAN DEFAULT FALSE NOT NULL, preferenceWeight DOUBLE DEFAULT 0.3 NOT NULL)");
            statement.execute("INSERT INTO maa_user(accountNumber,username,passwordHash,createdAt) VALUES('1003','fixture','fixture',CURRENT_TIMESTAMP)");
        }
        try (var factory = new Configuration().addAnnotatedClass(User.class)
                .setProperty("hibernate.connection.url", url).setProperty("hibernate.connection.username", "sa")
                .setProperty("hibernate.connection.password", "").setProperty("hibernate.hbm2ddl.auto", "update")
                .buildSessionFactory()) {
            try (var session = factory.openSession()) {
                var tx = session.beginTransaction(); var user = session.find(User.class, 1L);
                assertEquals(PopupPreferences.defaults(), user.getSelectionPreferences());
                user.setSelectionPreferences(new PopupPreferences(false, true, false, true));
                tx.commit();
            }
            try (var session = factory.openSession()) {
                assertEquals(new PopupPreferences(false,true,false,true), session.find(User.class, 1L).getSelectionPreferences());
                assertEquals(PopupPreferences.defaults(), new User().getSelectionPreferences());
            }
        }
    }
}
